/*
Характеризационные тесты текста «Начало осмотра».

Снимают дословный вывод компонента до переноса склейки в
`src/lib/text/nachalo`: двойной пробел в ст. 23 ч.4, «его/ее»,
«Освидетельствован/а» и хвостовые пробелы разметки. После переноса
вывод должен остаться байт в байт.
*/

// вывод компонента при заданных значениях полей стора
function nachaloText(
  configure?: (store: StatusStore) => void,
  overrides?: Partial<StatusState>
): string {
  const store = createStatusStore(overrides);
  // фиксированная дата, чтобы текст не зависел от дня запуска
  store.dispatch(setText("dataOsmotra", "2020-05-05"));

  if (configure) {
    configure(store);
  }

  const { container } = renderWithStatus(<NachaloList />, store);
  return container.textContent || "";
}

// срез «Общее состояние» с незаполненными радиогруппами
function emptyRadioOverrides(
  nedobrovolno = false
): Partial<StatusState> {
  const store = createStatusStore();
  const sostoyanie = store.getState().sostoyanie;

  return {
    sostoyanie: {
      ...sostoyanie,
      nedobrovolno: { isChecked: nedobrovolno },
      mestoOsmotra: { number: undefined },
      nedobrovolnoPrichiny: { number: undefined },
      nedobrovolnoPunkt: { number: undefined }
    }
  };
}

